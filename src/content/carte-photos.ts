/**
 * La carte photos — Jalal's shoot (November 2026): one hand-framed square per dish.
 *
 * - `file` is the original in "jalal photos/", renamed after the platter. Originals are never modified.
 * - `crop` is the square window cut from it: centre (cx, cy) as fractions of the photo's width and height,
 *   side `s` as a fraction of its width. Framings were chosen by eye to keep each dish central and to
 *   leave out hands, glasses and cutlery wherever the shot allowed it.
 * - `confidence: "check"` marks a match that is plausible but should be confirmed by the kitchen.
 *
 * Outputs are generated by `pnpm assets:carte` into public/images/carte/<itemId>-<width|full>.<avif|webp>.
 * These files feed the la carte page only — the home page and its pipeline (`pnpm assets:photos`) are untouched.
 * Plain data only: this file is imported by both the app and the Node asset script.
 */

