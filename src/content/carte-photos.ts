export const hasCartePhoto = (itemId: string): boolean => itemId in cartePhotos;

export const carteSrcSet = (itemId: string, ext: "avif" | "webp"): string =>
  CARTE_WIDTHS.map((w) => `/images/carte/${itemId}-${w}.${ext} ${w}w`).join(", ");

/** The enlarged photo shown by the viewer: `<id>-full.avif` / `<id>-full.webp`. */
export const carteFullSrc = (itemId: string, ext: "avif" | "webp"): string =>
  `/images/carte/${itemId}-full.${ext}`;

/** Fallback `src`: the largest WebP. */
export const carteSrc = (itemId: string): string => `/images/carte/${itemId}-${CARTE_WIDTHS.at(-1)}.webp`;
