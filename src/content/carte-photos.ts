export type CartePhoto = {
  file: string;
  crop: { cx: number; cy: number; s: number };
  confidence: "sure" | "check";
  note?: string;
};

const sure = (file: string, cx: number, cy: number, s: number, note?: string): CartePhoto => ({
  file,
  crop: { cx, cy, s },
  confidence: "sure",
  ...(note ? { note } : {}),
});
const check = (file: string, cx: number, cy: number, s: number, note: string): CartePhoto => ({
  file,
  crop: { cx, cy, s },
  confidence: "check",
  note,
});

