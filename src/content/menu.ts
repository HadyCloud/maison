import { categoryAr, itemAr, perPersonAr } from "./menu-ar";
import { type MenuItem, type MenuTag, menuSchema } from "./menu-schema";

type Seed = {
  id: string;
  fr: string;
  en: string;
  dFr?: string;
  dEn?: string;
  price: number | null;
  pieces?: number;
  tags?: MenuTag[];
  photos?: string[];
  perPerson?: boolean;
  dineIn?: boolean;
};

const SIGNATURES = new Set([
  "moutabbal-noix-grenade",
  "houmous-basilic",
  "houmous-betterave",
  "labneh-makdous",
  "chankliche",
  "trilogie-houmous",
]);

function item(s: Seed): MenuItem {
  const signature = SIGNATURES.has(s.id);
  const tags = [...(s.tags ?? []), ...(signature ? (["SIGNATURE"] as const) : [])];
  return {
    id: s.id,
    name: { fr: s.fr, en: s.en, ar: itemAr[s.id]?.n ?? s.en },
    description: { fr: s.dFr ?? "", en: s.dEn ?? "", ar: itemAr[s.id]?.d ?? "" },
    price: s.price,
    ...(s.perPerson ? { priceNote: { fr: "par personne", en: "per person", ar: perPersonAr } } : {}),
    ...(s.pieces ? { pieces: s.pieces } : {}),
    tags,
    ...(signature ? { signature: true } : {}),
    photoIds: s.photos ?? [],
    priceConfirmed: true,
    dineIn: s.dineIn ?? true,
  };
}

